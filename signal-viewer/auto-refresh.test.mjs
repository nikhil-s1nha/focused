import assert from 'node:assert/strict';
import {DRAFT_IDS,saveDraftState,restoreDraftState,createVersionWatcher} from './auto-refresh.js';
const fields=new Map(DRAFT_IDS.map(id=>[id,{type:'text',value:id+' draft'}]));
fields.set('unrelated-private-input',{type:'text',value:'must not persist'});
const document={getElementById:id=>fields.get(id)};
const values=new Map();const storage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
assert.equal(saveDraftState({document,storage,scrollX:4,scrollY:321,now:10000}),true);
const saved=JSON.parse([...values.values()][0]);
assert.deepEqual(Object.keys(saved.drafts),DRAFT_IDS);
assert.equal(JSON.stringify(saved).includes('must not persist'),false);
for(const id of DRAFT_IDS)fields.get(id).value='';
let scrolled;
assert.equal(restoreDraftState({document,storage,scrollTo:(x,y)=>scrolled=[x,y],now:11000}),true);
assert.equal(fields.get('bench-custom-marker').value,'bench-custom-marker draft');
assert.deepEqual(scrolled,[4,321]);assert.equal(values.size,0);
const denied={getItem(){throw Error('storage unavailable');},setItem(){throw Error('storage unavailable');},removeItem(){}};
assert.equal(saveDraftState({document,storage:denied}),false);
assert.equal(restoreDraftState({document,storage:denied}),false);
let step=0,reloads=0;const scheduled=[];
const watcher=createVersionWatcher({getVersion:async()=>{step++;if(step===2)throw Error('server restarting');return step<4?'v1':'v2';},onChange:()=>reloads++,schedule:(fn,ms)=>scheduled.push([fn,ms])});
await watcher.poll();assert.equal(reloads,0);assert.equal(scheduled[0][1],1500);
await scheduled.shift()[0]();assert.equal(reloads,0);
await scheduled.shift()[0]();assert.equal(reloads,0);
await scheduled.shift()[0]();assert.equal(reloads,1);assert.equal(scheduled.length,0);
await watcher.poll();assert.equal(reloads,1);
console.log('PASS: 1.5s asset polling, temporary restart tolerance, one reload, allowlisted drafts/scroll only, no hardware controls persisted or invoked.');
