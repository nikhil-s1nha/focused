import assert from 'node:assert/strict';
import fs from 'node:fs';
import {benchReception} from './bench-panel.js';
const recording={active:true,stage:'capturing_untrusted_bench_bytes',remote_status:{restart_count:1,max_restarts:3,last_frame_age_seconds:.3,frames_received_total:100}};
const capture={completed:false,sample_age_seconds:.4,phases:[{frame_count:100}]};
assert.equal(benchReception(recording,capture).text,'Receiving');
assert.equal(benchReception(recording,capture).fresh,true);
assert.equal(benchReception({...recording,active:false},capture).text,'Stopped');
assert.equal(benchReception({...recording,stage:'restarting_stream'},capture).text,'Restarting');
assert.equal(benchReception(recording,{...capture,sample_age_seconds:3}).text,'No frames');
assert.equal(benchReception({...recording,remote_status:{...recording.remote_status,last_frame_age_seconds:3}},capture).text,'No frames');
assert.equal(benchReception({...recording,remote_status:{...recording.remote_status,last_frame_age_seconds:null}},capture).text,'No frames');
assert.equal(benchReception(recording,{...capture,phases:[]}).fresh,false);
assert.equal(benchReception(recording,{...capture,completed:true}).fresh,false);
assert.equal(benchReception(recording,capture,{captureUnavailable:true}).fresh,false);
assert.equal(benchReception(recording,capture,{recordingAvailable:false}).text,'No frames · controller unavailable');
const exhausted={...recording,remote_status:{restart_count:3,max_restarts:3,last_frame_age_seconds:20,frames_received_total:100,recovery_exhausted:true}};
assert.equal(benchReception(exhausted,capture).text,'No frames · 3 restarts tried');
assert.equal(benchReception(exhausted,capture).restartCount,3);
assert.equal(benchReception({...exhausted,stage:'restarting_stream'},capture).text,'No frames · 3 restarts tried');
assert.equal(benchReception({...exhausted,remote_status:{...exhausted.remote_status,stage:'restarting_stream'}},capture).text,'No frames · 3 restarts tried');
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
assert.ok(!html.includes('120 seconds'));
assert.ok(!html.includes('02:00'));
assert.ok(html.includes('<h2>Record</h2>'));
assert.ok(!html.includes('bench-object-confirm'));
assert.ok(html.includes('Raw counts · unverified'));
assert.ok(html.includes('<details class="event-panel bench-diagnostics">'));
assert.ok(html.includes('id="bench-reception-pill"'));
console.log('PASS: Receiving requires real fresh frames/server age; restarting, stale, exhausted and stopped statuses are distinct; no capture time limit.');
